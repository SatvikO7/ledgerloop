class ScoredRun(Protocol):
    """What the report needs from anything it scores.

    Both :class:`~ledgerloop.eval.baselines.BaselineRun` and
    :class:`~ledgerloop.matching.pipeline.MatchRun` satisfy this, which is the
    point: the report renders a baseline and the real system through the same
    code path, so the comparison cannot be flattered by rendering one of them
    more generously than the other.

    Every member is declared read-only, so a dataclass field and a computed
    property both satisfy it -- B0 counts its joins as it goes while the matcher
    derives them from the tier outcomes, and neither has to reshape itself.
    """

    @property
    def name(self) -> str: ...

    @property
    def description(self) -> str: ...

    @property
    def predictions(self) -> tuple[PredictedLink, ...]: ...

    @property
    def wall_clock_ms(self) -> int: ...

    @property
    def credits_seen(self) -> int: ...

    @property
    def credits_with_utr(self) -> int: ...

    @property
    def credits_without_utr(self) -> int: ...

    @property
    def credits_joined(self) -> int: ...

    @property
    def settlements_seen(self) -> int: ...

    @property
    def settlements_joined(self) -> int: ...

    @property
    def settlements_unjoined(self) -> int: ...


@dataclass(frozen=True)
class EvaluatedRun:
    """One system's predictions, already scored.

    ``calibration`` is present only for a run that carried a fitted bundle. A
    baseline has no probabilities to calibrate and an uncalibrated run has only
    the tiers' provisional ones, so in both cases the section is *absent* rather
    than rendered empty -- the same rule the tier table follows.
    """

    system: ScoredRun
    metrics: RunMetrics
    calibration: CalibrationEvaluation | None = None
    exceptions: tuple[ReconException, ...] = ()
    coverage: ExceptionCoverage | None = None
    resolutions: tuple[AutoResolution, ...] = ()
    rounding_spent_minor: int = 0
    cost: CostLedger | None = None
    llm_accepted: int = 0
    llm_rejected_ungrounded: int = 0
    llm_rejected_unverified: int = 0
    llm_prose_rewritten: int = 0

    candidates_proposed: int = 0
    """Candidate yield on the evaluation unit, before the decision policy ruled.

    Zero for a baseline, which has no proposal stage separate from its output;
    :func:`_comparison_table` renders that case as the asserted-link count with
    a note rather than as a yield of zero.
    """

    auto_matched: int = 0
    """Evaluation-unit links the run committed. Equals TP + FP by construction."""

    bundle: CalibrationBundle | None = None
    """The fitted bundle this run applied, for the Phase 2.1 calibration verdict.

    The report needs the *fit* and not only its output to say whether the layer
    changed anything: a degenerate logistic and a one-block isotonic are facts
    about the model, and no metric computed downstream of them can state them.
    """

    review_band_probabilities: tuple[float, ...] = ()
    """The distinct calibrated probabilities the run's decisions carried.

    Two values -- 0.5 and 1.0 -- is a bimodal run, and a bimodal run has an
    empty review band whatever `tau_low` and `tau_high` are set to. Collected
    because the conclusion is only checkable if the distribution is printed.
    """

    scope: str = ""
    """A note on what this row was measured over, when it is not the main split.

    B2 runs on `dev` rather than `test` (PLAN.md §9.2), and a comparison table
    whose rows come from different corpora has to say so in the row itself --
    a footnote is where that kind of qualification goes to be missed.
    """

    review_queue: int = 0
    """Evaluation-unit links the policy deliberately sent to a human.

    Reported rather than folded into the false negatives, because they are a
    different thing: a link the system declined to commit and *said so* is the
    system working, and a link it never found is the system missing.
    """

    negatives: tuple[tuple[str, str, int], ...] = ()
    """``(label, what it means, count)`` -- where the recall that is missing went.

    A recall of 0.44 is a number; "99 links lost to A07, 84 to contested
    duplicates nothing can disambiguate" is a finding. PLAN.md D8 asks for the
    second, so the counters the tiers already keep are surfaced here instead of
    staying in a run object nobody reads.
    """


def _pct(value: float) -> str:
    return f"{value * 100:.2f}%"


def _ratio_cell(value: float, denominator: int) -> str:
    """Render a ratio, or ``n/a`` when its denominator is empty.

    A zero denominator is not a score of zero. Printing ``0.00%`` for "there was
    nothing to measure" is the single most common way an evaluation report
    misleads, and it costs one branch to not do it.
    """
    return _pct(value) if denominator > 0 else "n/a"


