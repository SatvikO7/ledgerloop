"""Render ``EVALUATION.md``. Nothing in it is hand-typed.

PLAN.md §9.4: "Every metric regenerated by one command: ``make eval``." That
rules out a document anyone edits, so this module owns the whole file and
``EVALUATION.md`` is gitignored -- a committed report is a report that can be
quietly corrected.

**No timestamp appears anywhere in the output**, so a diff between two runs
shows a change in the *system* rather than a change in the clock. That is the
same discipline the generator's emitters follow, and for the same reason.

The one exception is the measured timing pair -- wall clock and throughput,
which PLAN.md §9.1 lists among the secondary metrics. Those genuinely differ
run to run. They are confined to a single labelled block that says so, rather
than being dropped (which would lose a required metric) or left unmarked (which
would leave a reader unable to tell a real regression from scheduler noise).

The document reports what it has and says so about what it does not. Rows for
metrics that no implemented step produces yet -- exception recall, calibration,
the B1/B2/B3 baselines -- are rendered as pending with the step that will fill
them, never as a zero. A zero for an unbuilt component is a false measurement.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from ledgerloop.eval.metrics import PredictedLink, evaluation_links_by_class
from ledgerloop.eval.reliability import CalibrationEvaluation
from ledgerloop.eval.truth_io import DatasetManifest
from ledgerloop.matching.calibration import ReliabilityDiagram
from ledgerloop.models.metrics import RunMetrics
from ledgerloop.models.truth import GroundTruth
from ledgerloop.money import format_minor

__all__ = ["PENDING_BASELINES", "EvaluatedRun", "ScoredRun", "render_report", "write_report"]

#: Baselines PLAN.md §9.2 specifies that no implemented step produces yet.
#: Listed so the table shows the shape of the finished comparison rather than
#: implying what is built so far is the whole story.
PENDING_BASELINES: tuple[tuple[str, str, str], ...] = (
    ("B1", "Exact + fuzzy -- the typical hackathon submission", "Step 10"),
    ("B2", "LLM-only, run on the 60-record dev split", "Step 10"),
    ("B3", "LedgerLoop, full ladder", "Step 8"),
)

_PENDING = "_pending_"


class ScoredRun(Protocol):
    """What the report needs from anything it scores.

    Both :class:`~ledgerloop.eval.baselines.BaselineRun` and
    :class:`~ledgerloop.matching.pipeline.MatchRun` satisfy this, which is the
    point: the report renders a baseline and the real system through the same
    code path, so the comparison cannot be flattered by rendering one of them
    more generously than the other.

    Every member is declared read-only, so a dataclass field and a computed
    property both satisfy it -- B0 counts its joins as it goes while the matcher
    derives them from the tier outcomes, and neither has to reshape itself.
    """

    @property
    def name(self) -> str: ...

    @property
    def description(self) -> str: ...

    @property
    def predictions(self) -> tuple[PredictedLink, ...]: ...

    @property
    def wall_clock_ms(self) -> int: ...

    @property
    def credits_seen(self) -> int: ...

    @property
    def credits_with_utr(self) -> int: ...

    @property
    def credits_without_utr(self) -> int: ...

    @property
    def credits_joined(self) -> int: ...

    @property
    def settlements_seen(self) -> int: ...

    @property
    def settlements_joined(self) -> int: ...

    @property
    def settlements_unjoined(self) -> int: ...


@dataclass(frozen=True)
class EvaluatedRun:
    """One system's predictions, already scored.

    ``calibration`` is present only for a run that carried a fitted bundle. A
    baseline has no probabilities to calibrate and an uncalibrated run has only
    the tiers' provisional ones, so in both cases the section is *absent* rather
    than rendered empty -- the same rule the tier table follows.
    """

    system: ScoredRun
    metrics: RunMetrics
    calibration: CalibrationEvaluation | None = None


def _pct(value: float) -> str:
    return f"{value * 100:.2f}%"


def _ratio_cell(value: float, denominator: int) -> str:
    """Render a ratio, or ``n/a`` when its denominator is empty.

    A zero denominator is not a score of zero. Printing ``0.00%`` for "there was
    nothing to measure" is the single most common way an evaluation report
    misleads, and it costs one branch to not do it.
    """
    return _pct(value) if denominator > 0 else "n/a"


def _header(manifest: DatasetManifest, truth: GroundTruth) -> list[str]:
    return [
        "# EVALUATION.md",
        "",
        "Generated by `make eval`. Every number below is computed; nothing is hand-typed,",
        "and the file carries no timestamp so two runs over the same data diff to nothing.",
        "",
        "| Dataset | |",
        "|---|---|",
        f"| Split | `{manifest.split.value}` |",
        f"| Difficulty | `{manifest.difficulty.value}` |",
        f"| Seed | `{manifest.seed}` |",
        f"| Generator version | `{manifest.generator_version}` |",
        f"| Records | {len(truth.records)} |",
        f"| Evaluation links (`PAYMENT_CREDITED_AS`) | {len(truth.evaluation_pairs)} |",
        "",
        "The atomic unit of evaluation is the `PAYMENT_CREDITED_AS` link -- a",
        "`(payment, bank_txn)` pair. Structural edges are excluded: the sources assert",
        "them, so counting them would inflate every score below. See `ARCHITECTURE.md` §2.",
        "",
    ]


def _headline(run: EvaluatedRun) -> list[str]:
    metrics = run.metrics
    links = metrics.link_metrics
    predicted = (links.true_positives + links.false_positives) if links else 0

    exception_recall = (
        _pct(metrics.exception_recall)
        if metrics.exceptions_by_class
        else f"{_PENDING} (no exception classifier before Step 8)"
    )
    calibration = (
        f"ECE {metrics.calibration.ece:.4f} over {metrics.calibration.sample_count} "
        f"residual links"
        if metrics.calibration
        else f"{_PENDING} (run without `--calibration`)"
    )

    return [
        f"## {run.system.name} -- {run.system.description}",
        "",
        "### The headline three (PLAN.md §9.1)",
        "",
        "| Metric | Value | Target |",
        "|---|---|---|",
        f"| Auto-match precision | {_ratio_cell(metrics.auto_match_precision, predicted)} | "
        "≥ 99.00% |",
        f"| Match rate | {_pct(metrics.match_rate)} | ≥ 85.00% |",
        f"| Exception recall | {exception_recall} | ≥ 95.00% |",
        f"| Calibration | {calibration} | -- |",
        "",
    ]


def _link_table(run: EvaluatedRun) -> list[str]:
    links = run.metrics.link_metrics
    if links is None:  # pragma: no cover - evaluate() always populates this
        return []

    predicted = links.true_positives + links.false_positives
    actual = links.true_positives + links.false_negatives
    return [
        "### Link-level detail",
        "",
        "| | |",
        "|---|---|",
        f"| True positives | {links.true_positives} |",
        f"| False positives | {links.false_positives} |",
        f"| False negatives | {links.false_negatives} |",
        f"| Precision | {_ratio_cell(links.precision, predicted)} |",
        f"| Precision 95% CI (Wilson) | [{links.precision_ci_low:.4f}, "
        f"{links.precision_ci_high:.4f}] |",
        f"| Recall | {_ratio_cell(links.recall, actual)} |",
        f"| F1 | {links.f1:.4f} |",
        f"| **False-positive cost** | **{format_minor(links.false_positive_cost_minor)}** |",
        "",
        "The interval is a Wilson score interval, not the normal approximation. At",
        "these sample sizes the normal approximation returns `[1.0, 1.0]` from a clean",
        "run, claiming certainty this data cannot support.",
        "",
        "False-positive cost is the money the system declared reconciled that was not.",
        "It is a rupee figure rather than a ratio because that is the form in which a",
        "finance team experiences a wrong auto-match.",
        "",
    ]


def _money_table(run: EvaluatedRun) -> list[str]:
    metrics = run.metrics
    total = metrics.reconciled_minor + metrics.outstanding_minor
    return [
        "### Money view",
        "",
        "| | |",
        "|---|---|",
        f"| Reconciled | {format_minor(metrics.reconciled_minor)} |",
        f"| Outstanding | {format_minor(metrics.outstanding_minor)} |",
        f"| Total across evaluation links | {format_minor(total)} |",
        f"| Unmatchable records (the honest ceiling) | {metrics.unmatchable_count} |",
        f"| Unmatchable impact | {format_minor(metrics.unmatchable_impact_minor)} |",
        "",
        "Unmatchable records are irreconcilable without data outside the three sources.",
        "They are excluded from the match-rate denominator and reported here instead, so",
        "a real ceiling is never presented as a model failure.",
        "",
    ]


def _class_recall_table(run: EvaluatedRun, truth: GroundTruth) -> list[str]:
    rows = run.metrics.recall_by_anomaly_class
    if not rows:  # pragma: no cover - every dataset carries labelled links
        return []

    classes = evaluation_links_by_class(truth)
    lines = [
        "### Recall by anomaly class",
        "",
        "Every class present in the data appears, including the ones that score zero.",
        "A link is attributed to each anomaly touching either of its endpoints, so a link",
        "broken in two ways appears in two rows and the counts do not sum to the total.",
        "",
        "| Class | Links | Recall |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| `{anomaly.value}` | {len(classes.get(anomaly, frozenset()))} | {_pct(recall)} |"
        for anomaly, recall in sorted(rows.items(), key=lambda item: item[0].value)
    )
    lines.append("")
    return lines


def _diagnostics(run: EvaluatedRun) -> list[str]:
    system = run.system
    return [
        "### Why it scores the way it does",
        "",
        "| | |",
        "|---|---|",
        f"| Bank credits read | {system.credits_seen} |",
        f"| ...carrying a recoverable UTR | {system.credits_with_utr} |",
        f"| ...with no UTR (A07, plus the unrelated noise rows) | "
        f"{system.credits_without_utr} |",
        f"| ...joined to a settlement | {system.credits_joined} |",
        f"| Settlements read | {system.settlements_seen} |",
        f"| ...reached by at least one credit | {system.settlements_joined} |",
        f"| ...never joined | {system.settlements_unjoined} |",
        f"| Links asserted | {len(system.predictions)} |",
        "",
        "#### Measured timings",
        "",
        "The only figures in this document that differ between two runs over the same",
        "data. Everything above is deterministic.",
        "",
        "| | |",
        "|---|---|",
        f"| Wall clock | {system.wall_clock_ms} ms |",
        f"| Throughput | {run.metrics.records_per_second:,.0f} records/sec |",
        "",
    ]


def _tier_table(run: EvaluatedRun) -> list[str]:
    """Candidate yield beside auto-matches. They are not the same number.

    A tier that proposes a hundred candidates and auto-matches forty has not
    performed like one that proposes forty and auto-matches forty: the gap is
    the review queue a finance team has to staff. Reporting a single figure
    would let an over-eager proposal stage hide behind a cautious policy, or a
    cautious policy hide behind an eager proposer.

    Tiers no implemented step produces are absent rather than shown at zero. A
    zero for an unbuilt component is a false measurement.
    """
    rows = run.metrics.tier_contributions
    if not rows:
        return []

    lines = [
        "### Tier contribution",
        "",
        "| Tier | Candidates proposed | Auto-matched | Marginal | LLM calls | Wall clock |",
        "|---|---|---|---|---|---|",
    ]
    lines.extend(
        f"| `{row.tier.name}` | {row.candidates_proposed} | {row.auto_matched} | "
        f"{row.marginal_auto_matched} | {row.llm_calls} | {row.wall_clock_ms} ms |"
        for row in rows
    )
    lines.extend(
        [
            "",
            "`Marginal` is what the tier added over the ladder without it. Every tier here",
            "sees only what the previous ones left in the pool, so marginal equals total by",
            "construction -- an equality that stops holding at T4, whose re-run loop can",
            "revisit earlier residue.",
            "",
            "Candidates include the structural `ORDER_PAID_BY` and intermediate",
            "`SETTLEMENT_CREDITED_AS` edges, which are decided and audited but never scored:",
            "`ARCHITECTURE.md` §2 restricts the metrics to `PAYMENT_CREDITED_AS`.",
            "",
        ]
    )
    return lines


def _absent(diagram: ReliabilityDiagram | None, field: str) -> str:
    """One measure of a diagram that may not exist, rendered as ``--`` if it does not.

    An absent population is not a population that measured zero, and the report
    says so with a dash rather than a number nobody produced.
    """
    if diagram is None:
        return "--"
    value = getattr(diagram, field)
    if isinstance(value, float):
        return f"{value:.4f}"
    if field == "populated_bins":
        return f"{value} of {len(diagram.bins)}"
    return str(value)


def _reliability_rows(diagram: ReliabilityDiagram) -> list[str]:
    """The populated bins of one reliability diagram, as a table.

    Empty bins are omitted rather than printed as zeros. A bin nothing landed in
    is not a bin where the system was 0% accurate, and printing it that way is
    the same mistake as rendering an empty denominator as a score.
    """
    rows = [
        "| Confidence bin | n | Mean p | Observed | Gap |",
        "|---|---|---|---|---|",
    ]
    rows.extend(
        f"| `[{item.lower:.1f}, {item.upper:.1f})` | {item.count} | "
        f"{item.mean_probability:.4f} | {item.empirical_rate:.4f} | "
        f"{item.gap:+.4f} |"
        for item in diagram.bins
        if item.count > 0
    )
    return rows


def _calibration_section(run: EvaluatedRun) -> list[str]:
    """Calibration quality, over the two populations that answer different questions.

    PLAN.md D3: "when the system says 90% confident, it is right ~90% of the
    time". This is where that claim is checked, and both of its qualifications
    are printed beside it:

    * **Residual tiers only.** T0 and T1 bypass the blender, and folding ~70% of
      volume at p = 1.0 into the measurement would produce an ECE describing the
      shape of the corpus rather than the quality of the calibrator.
    * **Populated bins.** An ECE computed over one populated bin says nothing at
      all, and the count is printed so a reader can see that for themselves
      rather than take a small number as a good one.
    """
    view = run.calibration
    if view is None:
        return []

    asserted = view.asserted
    lines = [
        "### Calibration (PLAN.md §6.5, D3)",
        "",
        "Measured on the **residual tiers only** — T0 and T1 set their own probability",
        "from a count rather than a model, and including ~70% of volume at `p = 1.0`",
        "would measure the corpus rather than the calibrator (`ARCHITECTURE.md` §6, 4).",
        "",
        "| | Asserted | Contenders |",
        "|---|---|---|",
    ]
    contenders = view.contenders
    measures: tuple[tuple[str, str, str], ...] = (
        ("Links", str(asserted.sample_count), _absent(contenders, "sample_count")),
        ("...correct", str(asserted.positive_count), _absent(contenders, "positive_count")),
        ("ECE", f"{asserted.ece:.4f}", _absent(contenders, "ece")),
        ("Brier", f"{asserted.brier:.4f}", _absent(contenders, "brier")),
        (
            "Populated bins",
            f"{asserted.populated_bins} of {len(asserted.bins)}",
            _absent(contenders, "populated_bins"),
        ),
    )
    lines.extend(
        [
            *(f"| {label} | {left} | {right} |" for label, left, right in measures),
            "",
            "**Asserted** is what the system actually claimed: the residual links it",
            "auto-matched or referred, carrying the probability the fitted bundle gave",
            "them. **Contenders** is every pairing the residual tiers *considered*,",
            "including the ones they refused — a population the system never asserted",
            "and the blender never scores, shown because it is the only population on",
            "this corpus that contains wrong pairings at all.",
            "",
        ]
    )
    if asserted.populated_bins <= 1:
        lines.extend(
            [
                "> One populated bin. The ECE above is therefore a statement about the",
                "> corpus — the tiers refused everything they were unsure of — and not a",
                "> demonstration that the calibrator discriminates. Reported rather than",
                "> hidden: `CalibrationMetrics.populated_bins` exists for exactly this.",
                "",
            ]
        )
    lines.extend(["#### Reliability — asserted links", ""])
    lines.extend(_reliability_rows(asserted))
    lines.append("")
    if contenders is not None:
        lines.extend(["#### Reliability — every contender considered", ""])
        lines.extend(_reliability_rows(contenders))
        lines.append("")
    return lines


def _comparison_table(runs: Sequence[EvaluatedRun]) -> list[str]:
    lines = [
        "## System and baseline comparison (PLAN.md §9.2)",
        "",
        "Precision and match rate are orthogonal by design. A row that trades match",
        "rate for precision is making the trade this project argues for: in finance ops a",
        "wrong auto-match costs far more than a human reviewing an extra item, and the",
        "false-positive cost column is that argument in rupees.",
        "",
        "| # | System | Precision | Match rate | FP cost |",
        "|---|---|---|---|---|",
    ]
    for run in runs:
        links = run.metrics.link_metrics
        predicted = (links.true_positives + links.false_positives) if links else 0
        cost = format_minor(links.false_positive_cost_minor) if links else "--"
        lines.append(
            f"| {run.system.name} | {run.system.description} | "
            f"{_ratio_cell(run.metrics.auto_match_precision, predicted)} | "
            f"{_pct(run.metrics.match_rate)} | {cost} |"
        )
    lines.extend(
        f"| {name} | {description} | {_PENDING} | {_PENDING} | {_PENDING} ({step}) |"
        for name, description, step in PENDING_BASELINES
    )
    lines.append("")
    return lines


def render_report(
    runs: Sequence[EvaluatedRun], *, manifest: DatasetManifest, truth: GroundTruth
) -> str:
    """Render the whole document. Deterministic for a given input."""
    if not runs:
        raise ValueError("render_report needs at least one evaluated run")

    lines: list[str] = []
    lines.extend(_header(manifest, truth))
    lines.extend(_comparison_table(runs))
    for run in runs:
        lines.extend(_headline(run))
        lines.extend(_link_table(run))
        lines.extend(_calibration_section(run))
        lines.extend(_tier_table(run))
        lines.extend(_class_recall_table(run, truth))
        lines.extend(_money_table(run))
        lines.extend(_diagnostics(run))
    return "\n".join(lines).rstrip("\n") + "\n"


def write_report(path: Path, text: str) -> None:
    """Write the report with ``\\n`` endings on every platform."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
