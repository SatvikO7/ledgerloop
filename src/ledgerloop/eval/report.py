def _negative_analysis(run: EvaluatedRun) -> list[str]:
    """Where the missing recall went, and what the system said instead.

    PLAN.md D8 and §9.1: publish the classes that do badly. A recall figure with
    no account of its complement invites the reader to assume the misses are
    uniform noise; they are not, and every counter below is one the tiers were
    already keeping.

    The review queue is listed separately from the false negatives on purpose.
    A link the policy declined to commit *and flagged* is the precision-first
    design working as specified; a link nothing ever found is a gap. Adding them
    together would hide which of the two this system has.
    """
    links = run.metrics.link_metrics
    if links is None or not run.negatives:
        return []
    lines = [
        "### Honest negative analysis (PLAN.md §9.1, D8)",
        "",
        f"{links.false_negatives} evaluation links were not asserted. Where they went:",
        "",
        "| Cause | Count | What it means |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| {label} | {count} | {meaning} |" for label, meaning, count in run.negatives
    )
    lines.extend(
        [
            "",
            "The counts do not partition the misses: a settlement can be both contested",
            "and left unsolved, and one unmatched settlement accounts for as many links",
            "as it has payments. They are the reasons the ladder recorded, not a",
            "decomposition of the total.",
            "",
            f"**{run.review_queue}** evaluation-unit links were routed to a human rather",
            "than committed. That is a different outcome from a miss and is counted",
            "separately: a link the policy declined *and flagged* is the precision-first",
            "design working; a link nothing found is a gap.",
            "",
        ]
    )
    return lines


def _class_recall_table(run: EvaluatedRun, truth: GroundTruth) -> list[str]:
    rows = run.metrics.recall_by_anomaly_class
    if not rows:  # pragma: no cover - every dataset carries labelled links
        return []

    classes = evaluation_links_by_class(truth)
    lines = [
        "### Recall by anomaly class",
        "",
        "Every class present in the data appears, including the ones that score zero.",
        "A link is attributed to each anomaly touching either of its endpoints, so a link",
        "broken in two ways appears in two rows and the counts do not sum to the total.",
        "",
        "| Class | Links | Recall |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| `{anomaly.value}` | {len(classes.get(anomaly, frozenset()))} | {_pct(recall)} |"
        for anomaly, recall in sorted(rows.items(), key=lambda item: item[0].value)
    )
    lines.append("")
    return lines


def _diagnostics(run: EvaluatedRun) -> list[str]:
    """Why the row scores the way it does, and the one block that holds timings.

    Every measured timing in the document is here, and nothing else in the
    document is measured with a clock. That is what lets a reader diff two runs
    and see a change in the *system*: the only lines that can move are the ones
    under a heading that says they move.
    """
    system = run.system
    per_tier = [
        f"| {row.tier.name} | {row.wall_clock_ms} ms |"
        for row in run.metrics.tier_contributions
    ]
    return [
        "### Why it scores the way it does",
        "",
        "| | |",
        "|---|---|",
        f"| Bank credits read | {system.credits_seen} |",
        f"| ...carrying a recoverable UTR | {system.credits_with_utr} |",
        f"| ...with no UTR (A07, plus the unrelated noise rows) | "
        f"{system.credits_without_utr} |",
        f"| ...joined to a settlement | {system.credits_joined} |",
        f"| Settlements read | {system.settlements_seen} |",
        f"| ...reached by at least one credit | {system.settlements_joined} |",
        f"| ...never joined | {system.settlements_unjoined} |",
        f"| Links asserted | {len(system.predictions)} |",
        "",
        "#### Measured timings",
        "",
        "The only figures in this document that differ between two runs over the same",
        "data. Everything above is deterministic.",
        "",
        "| | |",
        "|---|---|",
        f"| Wall clock | {system.wall_clock_ms} ms |",
        f"| Throughput | {run.metrics.records_per_second:,.0f} records/sec |",
        *per_tier,
        "",
    ]


def _tier_table(run: EvaluatedRun) -> list[str]:
    """Candidate yield beside auto-matches. They are not the same number.

    A tier that proposes a hundred candidates and auto-matches forty has not
    performed like one that proposes forty and auto-matches forty: the gap is
    the review queue a finance team has to staff. Reporting a single figure
    would let an over-eager proposal stage hide behind a cautious policy, or a
    cautious policy hide behind an eager proposer.

    Tiers no implemented step produces are absent rather than shown at zero. A
    zero for an unbuilt component is a false measurement -- and from Step 10 a
    tier the ablation *switched off* is absent for the same reason.

    **Per-tier wall clock is not here.** It is a measured timing, and this
    module's contract is that every such figure lives in the single labelled
    ``#### Measured timings`` block. A stopwatch reading in an otherwise
    deterministic table would make a diff between two runs show scheduler noise
    rather than a change in the system, which is exactly what the no-timestamp
    rule exists to prevent.
    """
    rows = run.metrics.tier_contributions
    if not rows:
        return []

    lines = [
        "### Tier contribution",
        "",
        "| Tier | Candidates proposed | Auto-matched | Marginal | LLM calls |",
        "|---|---|---|---|---|",
    ]
    lines.extend(
        f"| `{row.tier.name}` | {row.candidates_proposed} | {row.auto_matched} | "
        f"{row.marginal_auto_matched} | {row.llm_calls} |"
        for row in rows
    )
    lines.extend(
        [
            "",
            "`Marginal` is what the tier added over the ladder without it. Every tier here",
            "sees only what the previous ones left in the pool, so marginal equals total by",
            "construction -- an equality that stops holding at T4, whose re-run loop can",
            "revisit earlier residue.",
            "",
            "Candidates include the structural `ORDER_PAID_BY` and intermediate",
            "`SETTLEMENT_CREDITED_AS` edges, which are decided and audited but never scored:",
            "`ARCHITECTURE.md` §2 restricts the metrics to `PAYMENT_CREDITED_AS`.",
            "",
        ]
    )
    return lines


def _absent(diagram: ReliabilityDiagram | None, field: str) -> str:
    """One measure of a diagram that may not exist, rendered as ``--`` if it does not.

    An absent population is not a population that measured zero, and the report
    says so with a dash rather than a number nobody produced.
    """
    if diagram is None:
        return "--"
    value = getattr(diagram, field)
    if isinstance(value, float):
        return f"{value:.4f}"
    if field == "populated_bins":
        return f"{value} of {len(diagram.bins)}"
    return str(value)


def _reliability_rows(diagram: ReliabilityDiagram) -> list[str]:
    """The populated bins of one reliability diagram, as a table.

    Empty bins are omitted rather than printed as zeros. A bin nothing landed in
    is not a bin where the system was 0% accurate, and printing it that way is
    the same mistake as rendering an empty denominator as a score.
    """
    rows = [
        "| Confidence bin | n | Mean p | Observed | Gap |",
        "|---|---|---|---|---|",
    ]
    rows.extend(
        f"| `[{item.lower:.1f}, {item.upper:.1f})` | {item.count} | "
        f"{item.mean_probability:.4f} | {item.empirical_rate:.4f} | "
        f"{item.gap:+.4f} |"
        for item in diagram.bins
        if item.count > 0
    )
    return rows


def _calibration_verdict(run: EvaluatedRun) -> list[str]:
    """Does the calibration layer change a single decision on this corpus?

    Phase 2.1 exists because the answer was **assemblable and never stated**.
    Every component of it was disclosed somewhere -- "single class" here, "one
    populated bin" there, `tau_high_is_fitted` in the config table, a decision
    breakdown further down -- and a reader had to gather four separate
    disclosures to reach a conclusion the document never drew. That is not
    dishonest and it is worse than saying it: a criticism a judge assembles
    themselves lands harder than one the author already made.

    So it is drawn here, and drawn **from the fitted bundle at render time**
    rather than typed. Every clause below is a fact read off the model this run
    applied, so the paragraph cannot survive the day the fit stops being
    degenerate -- which is exactly the day it should stop being printed.
    """
    bundle = run.bundle
    if bundle is None:
        return []

    blender = bundle.blender
    isotonic = bundle.calibrator
    selection = bundle.thresholds
    largest = max((abs(value) for value in blender.coefficients), default=0.0)
    constant = largest < 1e-9
    one_block = len(isotonic.values) == 1
    single_class = blender.positive_count == blender.sample_count
    probabilities = run.review_band_probabilities
    review_band_empty = run.review_queue == 0

    inert = constant and one_block and review_band_empty
    lines = [
        "#### Does this layer change any decision on this corpus?",
        "",
    ]
    if not inert:
        lines.extend(
            [
                "**Yes.** The fit is not degenerate on this corpus: the logistic has",
                f"non-zero coefficients (largest |β| = {largest:.3e}), the isotonic map",
                f"has {len(isotonic.values)} block(s), and the policy referred",
                f"{run.review_queue} link(s) to review. The numbers above are a",
                "measurement of the calibrator, not of the corpus.",
                "",
            ]
        )
        return lines

    lines.extend(
        [
            "**No — and that is the honest and the interesting answer.** Stated in one",
            "place rather than left to be assembled from four disclosures:",
            "",
            f"1. The residual tiers refuse rather than guess, so the fit population "
            f"is **single class**: {blender.positive_count} of "
            f"{blender.sample_count} training rows are positives"
            + (" — there is no contrast to learn from." if single_class else "."),
            f"2. Every logistic coefficient comes out **numerically zero** (largest "
            f"|β| = {largest:.3e}), leaving only the intercept "
            f"({blender.intercept:.2f}) — so the blender is a constant function.",
            f"3. The isotonic map collapses to **one block** over "
            f"{isotonic.sample_count} calibration rows: everything at or above "
            f"{isotonic.thresholds[0]:.6f} maps to {isotonic.values[0]:.4f}.",
            f"4. `tau_high` fits at **{selection.tau_high:.6f}**"
            + (" (target attained)" if selection.attained else " (target not attained)")
            + ", so only candidates the *tiers* already stamped 1.0 can auto-match.",
            f"5. The review band `τ_low < p < τ_high` is therefore **empty**: "
            f"{run.review_queue} link(s) were referred to review, and the run's "
            "decisions carry only "
            + ", ".join(f"`{value:.4f}`" for value in probabilities)
            + " — a bimodal distribution with nothing in between, so the three-way "
            "policy behaves two-way here.",
            "",
            "**Therefore the calibration layer cannot change a single decision on this",
            "corpus. Remove it and every number in this document is identical.** What",
            "the machinery buys is the *shape*: the day a tier starts proposing things",
            "that are sometimes wrong, there is a fitted model, a held-out split and a",
            "threshold-selection procedure already in place, and",
            "`CalibrationProvenance` still refuses at construction to fit on `test`.",
            "",
            "\"Confidence-calibrated\" therefore describes the **architecture** here,",
            "not a demonstrated behaviour. The report says which.",
            "",
        ]
    )
    return lines


def _calibration_section(run: EvaluatedRun) -> list[str]:
    """Calibration quality, over the two populations that answer different questions.

    PLAN.md D3: "when the system says 90% confident, it is right ~90% of the
    time". This is where that claim is checked, and both of its qualifications
    are printed beside it:

    * **Residual tiers only.** T0 and T1 bypass the blender, and folding ~70% of
      volume at p = 1.0 into the measurement would produce an ECE describing the
      shape of the corpus rather than the quality of the calibrator.
    * **Populated bins.** An ECE computed over one populated bin says nothing at
      all, and the count is printed so a reader can see that for themselves
      rather than take a small number as a good one.
    """
    view = run.calibration
    if view is None:
        return []

    asserted = view.asserted
    lines = [
        "### Calibration (PLAN.md §6.5, D3)",
        "",
        "Measured on the **residual tiers only** — T0 and T1 set their own probability",
        "from a count rather than a model, and including ~70% of volume at `p = 1.0`",
        "would measure the corpus rather than the calibrator (`ARCHITECTURE.md` §6, 4).",
        "",
        "| | Asserted | Contenders |",
        "|---|---|---|",
    ]
    contenders = view.contenders
    measures: tuple[tuple[str, str, str], ...] = (
        ("Links", str(asserted.sample_count), _absent(contenders, "sample_count")),
        ("...correct", str(asserted.positive_count), _absent(contenders, "positive_count")),
        ("ECE", f"{asserted.ece:.4f}", _absent(contenders, "ece")),
        ("Brier", f"{asserted.brier:.4f}", _absent(contenders, "brier")),
        (
            "Populated bins",
            f"{asserted.populated_bins} of {len(asserted.bins)}",
            _absent(contenders, "populated_bins"),
        ),
    )
    lines.extend(
        [
            *(f"| {label} | {left} | {right} |" for label, left, right in measures),
            "",
            "**Asserted** is what the system actually claimed: the residual links it",
            "auto-matched or referred, carrying the probability the fitted bundle gave",
            "them. **Contenders** is every pairing the residual tiers *considered*,",
            "including the ones they refused — a population the system never asserted",
            "and the blender never scores, shown because it is the only population on",
            "this corpus that contains wrong pairings at all.",
            "",
        ]
    )
    if asserted.populated_bins <= 1:
        lines.extend(
            [
                "> One populated bin. The ECE above is therefore a statement about the",
                "> corpus — the tiers refused everything they were unsure of — and not a",
                "> demonstration that the calibrator discriminates. Reported rather than",
                "> hidden: `CalibrationMetrics.populated_bins` exists for exactly this.",
                "",
            ]
        )
    lines.extend(_calibration_verdict(run))
    lines.extend(["#### Reliability — asserted links", ""])
    lines.extend(_reliability_rows(asserted))
    lines.append("")
    if contenders is not None:
        lines.extend(["#### Reliability — every contender considered", ""])
        lines.extend(_reliability_rows(contenders))
        lines.append("")
    return lines


QUEUE_PREVIEW = 10


def _exception_queue(run: EvaluatedRun) -> list[str]:
    """The deliverable: what a controller would actually work through.

    PLAN.md 8.2.2 -- "a bare 'unmatched' count is not a deliverable" -- and
    8.2.3, which fixes the ordering: **descending rupee impact**, never count and
    never class. One ₹4 lakh payout matters more than two hundred one-paise
    drifts, and any other sort order hides that.

    Only the top rows are printed in full. The point of the section is to show
    that every row carries a class, a price, a cause and an action; printing
    ninety of them would prove the same thing at ninety times the length.
    """
    exceptions = run.exceptions
    if not exceptions:
        return []

    coverage = run.coverage
    total = sum(item.impact_minor for item in exceptions)
    lines = [
        "### The exception queue (PLAN.md §8)",
        "",
        f"{len(exceptions)} exceptions covering {format_minor(total)}, sorted by rupee",
        "impact descending. Every row carries a class, a severity, a money figure, an",
        "evidence chain pointing back at source records, a root cause and an action.",
        "",
    ]
    if coverage is not None:
        lines.extend(
            [
                "| | |",
                "|---|---|",
                f"| Exceptions raised | {coverage.raised} |",
                f"| Records ground truth calls exceptions | {len(coverage.expected)} |",
                f"| ...covered by the queue | {len(coverage.covered_expected)} |",
                f"| **Exception recall** | **{_pct(coverage.recall)}** |",
                f"| Records unmatchable by construction | {len(coverage.unmatchable)} |",
                f"| ...covered by the queue | {len(coverage.covered_unmatchable)} "
                f"({_ratio_cell(coverage.unmatchable_recall, len(coverage.unmatchable))}) |",
                f"| Outgoing rows outside the unit | {coverage.out_of_scope} |",
                "",
                "Unmatchable records are counted on their own line and **not** inside the",
                "recall figure. Raising an exception for one is the correct behaviour --",
                "it is how the honest floor gets reported -- but crediting it in the",
                "headline would let a system inflate its recall by describing items nobody",
                "could have resolved. Outgoing rows are money leaving the account rather",
                "than a payout being reconciled, so they are outside the unit entirely and",
                "the count is printed rather than the rows being dropped quietly.",
                "",
            ]
        )
    lines.extend(
        [
            f"#### Highest impact ({min(QUEUE_PREVIEW, len(exceptions))} of {len(exceptions)})",
            "",
            "| Severity | Impact | Class | Subject | Confidence | Agent |",
            "|---|---|---|---|---|---|",
        ]
    )
    lines.extend(
        f"| {item.severity.value} | {format_minor(item.impact_minor)} | "
        f"`{item.exception_class.value}` | `{item.involved_refs[0].record_id}` | "
        f"{item.classification_confidence:.2f} | "
        f"{'bounded' if item.resolvable_by_agent else 'proposal only'} |"
        for item in exceptions[:QUEUE_PREVIEW]
    )
    top = exceptions[0]
    lines.extend(
        [
            "",
            "The top row in full, because a table cell cannot carry an evidence chain:",
            "",
            f"> **{top.exception_class.value}** · {top.severity.value} · "
            f"{format_minor(top.impact_minor)} · confidence "
            f"{top.classification_confidence:.2f}",
            ">",
            f"> {top.root_cause}",
            ">",
            f"> **Next:** {top.suggested_action}",
            ">",
            f"> Evidence ({len(top.evidence)} items), first three:",
        ]
    )
    lines.extend(f"> - {item.detail}" for item in top.evidence[:3])
    lines.append("")
    return lines


def _exception_class_table(run: EvaluatedRun) -> list[str]:
    counts = run.metrics.exceptions_by_class
    if not counts:
        return []
    impact: dict[str, int] = {}
    for item in run.exceptions:
        key = item.exception_class.value
        impact[key] = impact.get(key, 0) + item.impact_minor
    lines = [
        "#### Queue by class",
        "",
        "| Class | Count | Impact |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| `{name.value}` | {count} | {format_minor(impact.get(name.value, 0))} |"
        for name, count in counts.items()
    )
    lines.append("")
    return lines


def _confusion_matrix(run: EvaluatedRun) -> list[str]:
    """True anomaly class against predicted exception class.

    **Rectangular on purpose** -- eleven anomaly classes against thirteen
    exception classes (`ARCHITECTURE.md` §6, 5). The two vocabularies answer
    different questions: one describes what the generator did to the data, the
    other what the system concluded about it. A square matrix would be an
    identity nobody measured.

    An exception is attributed to every anomaly touching any record it names, so
    the rows do not partition the queue and do not sum to its size.
    """
    matrix = run.metrics.exception_confusion
    if not matrix:
        return []
    predicted = sorted({name for row in matrix.values() for name in row})
    lines = [
        "#### Anomaly → exception confusion",
        "",
        "| True anomaly | " + " | ".join(f"`{name}`" for name in predicted) + " |",
        "|---" * (len(predicted) + 1) + "|",
    ]
    for anomaly, row in matrix.items():
        cells = " | ".join(str(row.get(name, 0)) or "·" for name in predicted)
        lines.append(f"| `{anomaly}` | {cells} |")
    lines.extend(
        [
            "",
            "Rows may overlap: an exception naming a settlement, its payments and their",
            "orders is attributed to every anomaly touching any of them, so the rows do",
            "not partition the queue and do not sum to its size.",
            "",
        ]
    )
    return lines


def _auto_resolution(run: EvaluatedRun) -> list[str]:
    """The leash, printed. PLAN.md §8.3 bounds are config and are shown as such."""
    resolutions = run.resolutions
    if not resolutions:
        return []
    lines = [
        "#### Bounded auto-resolution (PLAN.md §8.3)",
        "",
        "The agent **proposes** and never posts to any real system. Each rule carries a",
        "hard bound, checked in code; a proposal that exceeds one is listed as refused",
        "with the bound named, never dropped.",
        "",
        "| Class | Rule | Bound | Applied | Refused |",
        "|---|---|---|---|---|",
    ]
    seen: dict[tuple[str, str, str], list[int]] = {}
    for item in resolutions:
        key = (item.exception_class.value, item.rule, item.bound)
        tally = seen.setdefault(key, [0, 0])
        tally[0 if item.applied else 1] += 1
    lines.extend(
        f"| `{cls}` | {rule} | {bound} | {tally[0]} | {tally[1]} |"
        for (cls, rule, bound), tally in seen.items()
    )
    lines.extend(
        [
            "",
            f"Rounding budget committed this run: "
            f"{format_minor(run.rounding_spent_minor)}.",
            "",
        ]
    )
    return lines


def _llm_section(run: EvaluatedRun) -> list[str]:
    """What the model cost, and what it was refused.

    PLAN.md §7.3 asks for calls per 100 records, tokens per run, actual spend
    and the equivalent paid cost. The last is the interesting one: actual spend
    is ₹0 by construction on the free tier, so the figure that quantifies what
    deterministic-first buys is what the same tokens would have cost had it not
    been.

    The refusal counts are printed beside the acceptance counts on purpose. "The
    model helped" is only a claim worth making if the same table says how often
    it was overruled -- by a grounding gate, or by the arithmetic.

    Absent entirely on a `--no-llm` run. A section of zeros for a component that
    did not run is a false measurement, which is the rule the tier table and the
    calibration section already follow.
    """
    cost = run.cost
    if cost is None:
        return []
    records = run.metrics.record_count
    return [
        "### LLM cost and refusals (PLAN.md §7.3)",
        "",
        "| | |",
        "|---|---|",
        f"| Calls | {cost.llm_calls} |",
        f"| Cache hits | {cost.cache_hits} ({_pct(cost.cache_hit_rate)}) |",
        f"| Calls per 100 records | {cost.calls_per_100_records(records):.2f} |",
        f"| Tokens | {cost.total_tokens:,} "
        f"({cost.prompt_tokens:,} prompt, {cost.completion_tokens:,} completion) |",
        f"| Actual cost | ₹{cost.actual_cost_inr:.2f} |",
        f"| Equivalent paid cost | ₹{cost.equivalent_paid_cost_inr:.2f} |",
        f"| Provider | `{cost.provider_used or 'none'}` |",
        "",
        "| Model output | Count |",
        "|---|---|",
        f"| Accepted after every gate | {run.llm_accepted} |",
        f"| Refused: cited records it was not given | {run.llm_rejected_ungrounded} |",
        f"| Refused: `verify_arithmetic` did not close | {run.llm_rejected_unverified} |",
        f"| Exception prose rewritten | {run.llm_prose_rewritten} of "
        f"{len(run.exceptions)} |",
        "",
        "A second identical run reaches a cache hit rate of 1.00 and makes **zero**",
        "live calls: the responses are content-hashed to disk and committed, so the",
        "claim is checkable rather than asserted. No number anywhere else in this",
        "document depends on a model: the links come from the deterministic ladder,",
        "the exception classes and amounts from Step 8's classifier, and every",
        "LLM-proposed link that reached a decision passed `verify_arithmetic` first.",
        "",
    ]


def _yield_cells(run: EvaluatedRun) -> tuple[str, str]:
    """Candidate yield and auto-matched, or the baseline's honest equivalent.

    A baseline has no proposal stage distinct from its output: every link it
    finds, it asserts. Rendering a yield of zero for that would read as "found
    nothing"; rendering the asserted count with a marker says what is true --
    the two numbers coincide because there is no policy between them.
    """
    links = run.metrics.link_metrics
    asserted = (links.true_positives + links.false_positives) if links else 0
    if run.candidates_proposed == 0 and run.auto_matched == 0:
        return (f"{asserted} †", str(asserted))
    return (str(run.candidates_proposed), str(run.auto_matched))


def _comparison_row(run: EvaluatedRun) -> str:
    metrics = run.metrics
    links = metrics.link_metrics
    predicted = (links.true_positives + links.false_positives) if links else 0
    actual = (links.true_positives + links.false_negatives) if links else 0
    proposed, matched = _yield_cells(run)
    exception_recall = (
        _pct(metrics.exception_recall) if metrics.exceptions_by_class else "n/a"
    )
    # PLAN.md 9.2 numbers the four systems B0-B3. The ladder's own name says
    # which tiers ran, which is the more useful label everywhere else in this
    # document -- so the comparison table carries both rather than choosing.
    name = run.system.name
    label = name if name.startswith("B") else f"B3 (`{name}`)"
    return (
        f"| {label} | {run.scope or '`test`'} | {proposed} | {matched} | "
        f"{_ratio_cell(metrics.auto_match_precision, predicted)} | "
        f"{_ratio_cell(links.recall if links else 0.0, actual)} | "
        f"{_pct(metrics.match_rate)} | {links.false_positives if links else 0} | "
        f"{format_minor(links.false_positive_cost_minor) if links else '--'} | "
        f"{exception_recall} |"
    )


def _b2_row(artifact: LLMBaselineArtifact | None) -> str:
    """B2 out of its saved artefact. Never re-run to render a document.

    A row is emitted even with no artefact at all, because the table's job is to
    show the shape of PLAN.md 9.2's comparison. What it must never do is fill
    that row with zeros: an absent measurement renders as pending, and the
    reader can tell the two cases apart.
    """
    if artifact is None:
        return (
            f"| B2 | `dev` | {_PENDING} | {_PENDING} | {_PENDING} | {_PENDING} | "
            f"{_PENDING} | {_PENDING} | {_PENDING} | n/a |"
        )
    marker = " §" if artifact.is_standin else ""
    if not artifact.ran:
        return (
            f"| B2 | `{artifact.split or 'dev'}` | {_PENDING} | {_PENDING} | "
            f"{_PENDING} | {_PENDING} | {_PENDING} | {_PENDING} | {_PENDING} | n/a |"
        )
    return (
        f"| B2{marker} | `{artifact.split}` ‡ | {artifact.links_asserted} † | "
        f"{artifact.links_asserted} | "
        f"{_ratio_cell(artifact.precision, artifact.true_positives + artifact.false_positives)} | "
        f"{_ratio_cell(artifact.recall, artifact.true_positives + artifact.false_negatives)} | "
        f"{_pct(artifact.match_rate)} | {artifact.false_positives} | "
        f"{format_minor(artifact.false_positive_cost_minor)} | n/a |"
    )


def _comparison_table(
    runs: Sequence[EvaluatedRun], llm_baseline: LLMBaselineArtifact | None = None
) -> list[str]:
    """PLAN.md §9.2's table: the four systems on the same ground truth.

    Candidate yield and auto-match rate sit in adjacent columns because they
    answer different questions -- reach and conviction -- and a single figure
    lets an over-eager proposal stage hide behind a cautious policy, or the
    reverse. Precision and recall likewise: a row that trades recall for
    precision is making the trade this project argues for, and the
    false-positive column is that argument in rupees.
    """
    lines = [
        "## System and baseline comparison (PLAN.md §9.2)",
        "",
        "All four systems, scored against the same link-level ground truth by the same",
        "`evaluate()` call. Precision and match rate are orthogonal by design: in finance",
        "ops a wrong auto-match costs far more than a human reviewing an extra item, and",
        "the false-positive cost column is that argument in rupees.",
        "",
        "| # | Split | Candidate yield | Auto-matched | Precision | Recall | "
        "Match rate | FP | FP cost | Exception recall |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    ordered = sorted(runs, key=lambda run: run.system.name)
    baselines = [run for run in ordered if run.system.name.startswith("B")]
    systems = [run for run in ordered if not run.system.name.startswith("B")]
    lines.extend(_comparison_row(run) for run in baselines)
    lines.append(_b2_row(llm_baseline))
    lines.extend(_comparison_row(run) for run in systems)
    lines.extend(
        [
            "",
            "† A baseline has no proposal stage separate from its output: every link it",
            "finds, it asserts. Yield and conviction coincide because there is no decision",
            "policy between them, which is exactly what the two columns exist to show.",
            "",
        ]
    )
    if llm_baseline is not None and llm_baseline.ran:
        lines.extend(
            [
                "‡ B2 is measured on the **60-order `dev` split**, not on `test`. PLAN.md",
                "§9.2 fixes that scope: an LLM-only baseline sends the corpus rather than its",
                "residual, so its token cost scales with the whole dataset and running it on",
                "`test` would spend a meaningful slice of a day's free-tier quota to",
                "demonstrate the same point. Its row is therefore **not** directly comparable",
                "to the rows above it, and the difference is stated here rather than left in",
                "a footnote nobody reads.",
                "",
            ]
        )
    if llm_baseline is not None and llm_baseline.is_standin:
        lines.extend(
            [
                "§ **B2 was not answered by a language model.** There is no provider key",
                "in this environment, so its prompts were answered by the documented",
                "stand-in reasoner in `eval/offline_provider.py`, which reads the prompt",
                "text and nothing else. Its **cost, cache, call and failure figures are",
                "measured machinery** -- the same prompt, cache, budget, schema and ledger a",
                "live provider goes through. Its **precision and recall are a property of",
                "that rule and are not a claim about any model.** What the row does",
                "demonstrate is architectural and reasoner-independent: output asserted",
                "with no `verify_arithmetic` behind it is asserted wrong as readily as",
                "right, and the token cost scales with the corpus rather than the residual.",
                "",
            ]
        )
    lines.extend(
        [
            "The systems' descriptions:",
            "",
        ]
    )
    lines.extend(
        f"- **{run.system.name if run.system.name.startswith('B') else 'B3'}** -- "
        f"{run.system.description}"
        for run in [*baselines, *systems]
    )
    lines.append(
        "- **B2** -- LLM-only: the whole corpus in the prompt, the model's answer "
        "asserted without a decision policy, a grounding gate or `verify_arithmetic`."
    )
    lines.append("")
    return lines


