"""Render ``EVALUATION.md``. Nothing in it is hand-typed.

PLAN.md §9.4: "Every metric regenerated by one command: ``make eval``." That
rules out a document anyone edits, so this module owns the whole file and
``EVALUATION.md`` is gitignored -- a committed report is a report that can be
quietly corrected.

**No timestamp appears anywhere in the output**, so a diff between two runs
shows a change in the *system* rather than a change in the clock. That is the
same discipline the generator's emitters follow, and for the same reason.

The one exception is the measured timing pair -- wall clock and throughput,
which PLAN.md §9.1 lists among the secondary metrics. Those genuinely differ
run to run. They are confined to a single labelled block that says so, rather
than being dropped (which would lose a required metric) or left unmarked (which
would leave a reader unable to tell a real regression from scheduler noise).

The document reports what it has and says so about what it does not. Rows for
metrics that no implemented step produces yet -- exception recall, calibration,
the B1/B2/B3 baselines -- are rendered as pending with the step that will fill
them, never as a zero. A zero for an unbuilt component is a false measurement.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from ledgerloop.eval.baselines import BaselineRun
from ledgerloop.eval.metrics import evaluation_links_by_class
from ledgerloop.eval.truth_io import DatasetManifest
from ledgerloop.models.metrics import RunMetrics
from ledgerloop.models.truth import GroundTruth
from ledgerloop.money import format_minor

__all__ = ["PENDING_BASELINES", "EvaluatedRun", "render_report", "write_report"]

#: Baselines PLAN.md §9.2 specifies that no implemented step produces yet.
#: Listed so the table shows the shape of the finished comparison rather than
#: implying B0 is the whole story.
PENDING_BASELINES: tuple[tuple[str, str, str], ...] = (
    ("B1", "Exact + fuzzy -- the typical hackathon submission", "Step 6"),
    ("B2", "LLM-only, run on the 60-record dev split", "Step 10"),
    ("B3", "LedgerLoop, full ladder", "Step 8"),
)

_PENDING = "_pending_"


@dataclass(frozen=True)
class EvaluatedRun:
    """One system's predictions, already scored."""

    baseline: BaselineRun
    metrics: RunMetrics


def _pct(value: float) -> str:
    return f"{value * 100:.2f}%"


def _ratio_cell(value: float, denominator: int) -> str:
    """Render a ratio, or ``n/a`` when its denominator is empty.

    A zero denominator is not a score of zero. Printing ``0.00%`` for "there was
    nothing to measure" is the single most common way an evaluation report
    misleads, and it costs one branch to not do it.
    """
    return _pct(value) if denominator > 0 else "n/a"


def _header(manifest: DatasetManifest, truth: GroundTruth) -> list[str]:
    return [
        "# EVALUATION.md",
        "",
        "Generated by `make eval`. Every number below is computed; nothing is hand-typed,",
        "and the file carries no timestamp so two runs over the same data diff to nothing.",
        "",
        "| Dataset | |",
        "|---|---|",
        f"| Split | `{manifest.split.value}` |",
        f"| Difficulty | `{manifest.difficulty.value}` |",
        f"| Seed | `{manifest.seed}` |",
        f"| Generator version | `{manifest.generator_version}` |",
        f"| Records | {len(truth.records)} |",
        f"| Evaluation links (`PAYMENT_CREDITED_AS`) | {len(truth.evaluation_pairs)} |",
        "",
        "The atomic unit of evaluation is the `PAYMENT_CREDITED_AS` link -- a",
        "`(payment, bank_txn)` pair. Structural edges are excluded: the sources assert",
        "them, so counting them would inflate every score below. See `ARCHITECTURE.md` §2.",
        "",
    ]


def _headline(run: EvaluatedRun) -> list[str]:
    metrics = run.metrics
    links = metrics.link_metrics
    predicted = (links.true_positives + links.false_positives) if links else 0

    exception_recall = (
        _pct(metrics.exception_recall)
        if metrics.exceptions_by_class
        else f"{_PENDING} (no exception classifier before Step 8)"
    )
    calibration = (
        f"ECE {metrics.calibration.ece:.4f}"
        if metrics.calibration
        else f"{_PENDING} (no blender before Step 7)"
    )

    return [
        f"## {run.baseline.name} -- {run.baseline.description}",
        "",
        "### The headline three (PLAN.md §9.1)",
        "",
        "| Metric | Value | Target |",
        "|---|---|---|",
        f"| Auto-match precision | {_ratio_cell(metrics.auto_match_precision, predicted)} | "
        "≥ 99.00% |",
        f"| Match rate | {_pct(metrics.match_rate)} | ≥ 85.00% |",
        f"| Exception recall | {exception_recall} | ≥ 95.00% |",
        f"| Calibration | {calibration} | -- |",
        "",
    ]


def _link_table(run: EvaluatedRun) -> list[str]:
    links = run.metrics.link_metrics
    if links is None:  # pragma: no cover - evaluate() always populates this
        return []

    predicted = links.true_positives + links.false_positives
    actual = links.true_positives + links.false_negatives
    return [
        "### Link-level detail",
        "",
        "| | |",
        "|---|---|",
        f"| True positives | {links.true_positives} |",
        f"| False positives | {links.false_positives} |",
        f"| False negatives | {links.false_negatives} |",
        f"| Precision | {_ratio_cell(links.precision, predicted)} |",
        f"| Precision 95% CI (Wilson) | [{links.precision_ci_low:.4f}, "
        f"{links.precision_ci_high:.4f}] |",
        f"| Recall | {_ratio_cell(links.recall, actual)} |",
        f"| F1 | {links.f1:.4f} |",
        f"| **False-positive cost** | **{format_minor(links.false_positive_cost_minor)}** |",
        "",
        "The interval is a Wilson score interval, not the normal approximation. At",
        "these sample sizes the normal approximation returns `[1.0, 1.0]` from a clean",
        "run, claiming certainty this data cannot support.",
        "",
        "False-positive cost is the money the system declared reconciled that was not.",
        "It is a rupee figure rather than a ratio because that is the form in which a",
        "finance team experiences a wrong auto-match.",
        "",
    ]


def _money_table(run: EvaluatedRun) -> list[str]:
    metrics = run.metrics
    total = metrics.reconciled_minor + metrics.outstanding_minor
    return [
        "### Money view",
        "",
        "| | |",
        "|---|---|",
        f"| Reconciled | {format_minor(metrics.reconciled_minor)} |",
        f"| Outstanding | {format_minor(metrics.outstanding_minor)} |",
        f"| Total across evaluation links | {format_minor(total)} |",
        f"| Unmatchable records (the honest ceiling) | {metrics.unmatchable_count} |",
        f"| Unmatchable impact | {format_minor(metrics.unmatchable_impact_minor)} |",
        "",
        "Unmatchable records are irreconcilable without data outside the three sources.",
        "They are excluded from the match-rate denominator and reported here instead, so",
        "a real ceiling is never presented as a model failure.",
        "",
    ]


def _class_recall_table(run: EvaluatedRun, truth: GroundTruth) -> list[str]:
    rows = run.metrics.recall_by_anomaly_class
    if not rows:  # pragma: no cover - every dataset carries labelled links
        return []

    classes = evaluation_links_by_class(truth)
    lines = [
        "### Recall by anomaly class",
        "",
        "Every class present in the data appears, including the ones that score zero.",
        "A link is attributed to each anomaly touching either of its endpoints, so a link",
        "broken in two ways appears in two rows and the counts do not sum to the total.",
        "",
        "| Class | Links | Recall |",
        "|---|---|---|",
    ]
    lines.extend(
        f"| `{anomaly.value}` | {len(classes.get(anomaly, frozenset()))} | {_pct(recall)} |"
        for anomaly, recall in sorted(rows.items(), key=lambda item: item[0].value)
    )
    lines.append("")
    return lines


def _diagnostics(run: EvaluatedRun) -> list[str]:
    baseline = run.baseline
    return [
        "### Why it scores the way it does",
        "",
        "| | |",
        "|---|---|",
        f"| Bank credits read | {baseline.credits_seen} |",
        f"| ...carrying a recoverable UTR | {baseline.credits_with_utr} |",
        f"| ...with no UTR (A07, plus the unrelated noise rows) | "
        f"{baseline.credits_without_utr} |",
        f"| ...joined to a settlement | {baseline.credits_joined} |",
        f"| Settlements read | {baseline.settlements_seen} |",
        f"| ...reached by at least one credit | {baseline.settlements_joined} |",
        f"| ...never joined | {baseline.settlements_unjoined} |",
        f"| Links asserted | {len(baseline.predictions)} |",
        "",
        "#### Measured timings",
        "",
        "The only figures in this document that differ between two runs over the same",
        "data. Everything above is deterministic.",
        "",
        "| | |",
        "|---|---|",
        f"| Wall clock | {baseline.wall_clock_ms} ms |",
        f"| Throughput | {run.metrics.records_per_second:,.0f} records/sec |",
        "",
    ]


def _baseline_table(runs: Sequence[EvaluatedRun]) -> list[str]:
    lines = [
        "## Baseline comparison (PLAN.md §9.2)",
        "",
        "| # | Baseline | Precision | Match rate | FP cost |",
        "|---|---|---|---|---|",
    ]
    for run in runs:
        links = run.metrics.link_metrics
        predicted = (links.true_positives + links.false_positives) if links else 0
        cost = format_minor(links.false_positive_cost_minor) if links else "--"
        lines.append(
            f"| {run.baseline.name} | {run.baseline.description} | "
            f"{_ratio_cell(run.metrics.auto_match_precision, predicted)} | "
            f"{_pct(run.metrics.match_rate)} | {cost} |"
        )
    lines.extend(
        f"| {name} | {description} | {_PENDING} | {_PENDING} | {_PENDING} ({step}) |"
        for name, description, step in PENDING_BASELINES
    )
    lines.append("")
    return lines


def render_report(
    runs: Sequence[EvaluatedRun], *, manifest: DatasetManifest, truth: GroundTruth
) -> str:
    """Render the whole document. Deterministic for a given input."""
    if not runs:
        raise ValueError("render_report needs at least one evaluated run")

    lines: list[str] = []
    lines.extend(_header(manifest, truth))
    lines.extend(_baseline_table(runs))
    for run in runs:
        lines.extend(_headline(run))
        lines.extend(_link_table(run))
        lines.extend(_class_recall_table(run, truth))
        lines.extend(_money_table(run))
        lines.extend(_diagnostics(run))
    return "\n".join(lines).rstrip("\n") + "\n"


def write_report(path: Path, text: str) -> None:
    """Write the report with ``\\n`` endings on every platform."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
